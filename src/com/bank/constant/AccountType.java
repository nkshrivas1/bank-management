package com.bank.constant;
//In Java, enumerations (enums) are a special
// type used to define a group of named constants.
//
// Enums help in readability, maintainability,
// and type safety in programs by assigning
// meaningful names to integer values.
//
// Mainly useful when we have a small set of
// possible values for an item like directions,
// days of week, etc.
public enum AccountType {
    CURRENT,
    SAVING,
}
